// Builds js/geoid-data.js: a coarse table of how far mean sea level sits
// above or below the WGS84 ellipsoid, for everywhere north of 58 degrees.
//
// ArcticDEM heights are measured from the ellipsoid (a smooth mathematical
// egg shape), not from sea level. In Iceland the two differ by about 65 m.
// The app subtracts this table from the terrain so summits read the way they
// do on a map. It only changes the numbers shown; radio results don't depend
// on it, because both ends of a link shift by nearly the same amount.
//
// Source: the EGM96 geoid model, via the egm96-universal package.
// Run:  node tools/make_geoid.mjs
import { writeFileSync } from 'node:fs';
import * as egm96 from 'egm96-universal';

const SOUTH = 58;
const NORTH = 90;
const STEP = Number(process.argv[2] ?? 1); // degrees between table entries

const rows = Math.round((NORTH - SOUTH) / STEP) + 1;
const cols = Math.round(360 / STEP) + 1;
const values = [];
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    values.push(Math.round(egm96.meanSeaLevel(SOUTH + r * STEP, -180 + c * STEP) * 10)); // decimetres
  }
}

// How good is the coarse table? Compare it with the full model at many points.
const lookup = (lat, lon) => {
  const fr = (lat - SOUTH) / STEP;
  const fc = (lon + 180) / STEP;
  const r = Math.min(rows - 2, Math.floor(fr));
  const c = Math.min(cols - 2, Math.floor(fc));
  const tr = fr - r;
  const tc = fc - c;
  const v = (rr, cc) => values[rr * cols + cc] / 10;
  return v(r, c) * (1 - tr) * (1 - tc) + v(r, c + 1) * (1 - tr) * tc + v(r + 1, c) * tr * (1 - tc) + v(r + 1, c + 1) * tr * tc;
};
let worst = 0;
let sumSq = 0;
let n = 0;
for (let lat = 60; lat < 84; lat += 0.137) {
  for (let lon = -180; lon < 180; lon += 0.291) {
    const err = Math.abs(lookup(lat, lon) - egm96.meanSeaLevel(lat, lon));
    worst = Math.max(worst, err);
    sumSq += err * err;
    n++;
  }
}
console.log(`step ${STEP} deg: ${rows} x ${cols} values, worst error ${worst.toFixed(2)} m, typical ${Math.sqrt(sumSq / n).toFixed(2)} m`);
console.log('Iceland check (64.24, -21.65):', egm96.meanSeaLevel(64.24, -21.65).toFixed(2), 'table', lookup(64.24, -21.65).toFixed(2));

if (process.argv[3] !== 'dry') {
  const lines = [];
  for (let r = 0; r < rows; r++) lines.push(values.slice(r * cols, (r + 1) * cols).join(','));
  writeFileSync(
    new URL('../js/geoid-data.js', import.meta.url),
    `// Generated by tools/make_geoid.mjs. Do not edit by hand.\n// Height of mean sea level (EGM96) above the WGS84 ellipsoid, in decimetres.\n// Rows run south to north from ${SOUTH} to ${NORTH} degrees, columns west to east from -180 to 180, every ${STEP} degree(s).\nexport const GEOID = {\n  south: ${SOUTH},\n  west: -180,\n  step: ${STEP},\n  rows: ${rows},\n  cols: ${cols},\n  decimetres: [\n${lines.map((l) => `    ${l},`).join('\n')}\n  ],\n};\n`,
  );
}
